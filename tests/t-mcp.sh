# ---- M9: local-only (no network, no stray spawns) -------------------------------
# The strongest available form of 'network disabled': run a full green verify with PATH
# reduced to the shell's own tools plus node, in a sandbox where nothing else exists —
# there is nothing to reach out with. The tool must still answer. (The fixture is fresh:
# the uninstall clauses above consumed their installs' records.)
new_fixture hermetic
SB="$WORK/hermetic-sb"; mkdir -p "$SB/bin"
for b in node python3 bash git awk sed grep cut ls sha256sum shasum cat dirname basename date head sort tr wc mktemp env pwd test command sleep; do
  p=$(command -v "$b" 2>/dev/null) && [ -e "$SB/bin/$b" ] || ln -s "$p" "$SB/bin/$b" 2>/dev/null
done
OUT=$(cd "$R" && printf '%s\n%s\n' \
  '{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocolVersion":"2024-11-05"}}' \
  '{"jsonrpc":"2.0","id":2,"method":"tools/call","params":{"name":"gob_verify","arguments":{}}}' \
  | env PATH="$SB/bin" HOME="$WORK" python3 "$SRC/tests/mcp-client.py" "node $MCP")
printf '%s' "$OUT" | grep -q 'gate: PASS'
check "M9 the server answers a full verify with nothing but the shell's own tools on PATH" "$?"
# the source tree carries no endpoint surface (PT-04's body, scoped to the new file)
ENDPOINTS=$(grep -nE 'https?://[^ ]*[^ )>`]|[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}|net\.connect|dgram|dns\.|tls\.|fetch\(' "$MCP" | grep -v 'npx -y @techgoblin/gobstack' || true)
[ -z "$ENDPOINTS" ]
check "M9 no endpoint, address or socket surface in the server source" "$?"
# the mcp verb is exercised through the npm shim (the one dispatcher)
OUT=$(printf '%s\n' '{"jsonrpc":"2.0","id":1,"method":"ping"}' | python3 "$SRC/tests/mcp-client.py" "node $SRC/bin/goblin.js mcp")
printf '%s' "$OUT" | grep -q '"id":1,"result":{}'
check "M9 the npm shim routes mcp under node (SH-M1: bash choked on the .js target)" "$?"

# ---- v3: registration is opt-in, and the surface says so ------------------------
# The default --write writes NO .mcp.json (the named removal); the flag is named on the
# brief and the done screen so the opt-in is discoverable, and the default install carries
# no registration a repo never asked for.
