# ---- M8: init --write --with-mcp-config registers MCP + the uninstall clause ------
# v3 enhance layer: the registration is OPT-IN — the named removal that pays for hooks
# emission. M8 drives the writer with the flag and pins ask-once in both directions.
new_fixture mcpcfg
GEN='{"mcpServers":{"gob":{"command":"npx","args":["-y","@techgoblin/gobstack","mcp"]}}}'
PRO=$(write_proposal "$R")
OUT=$(cd "$R" && bash "$SRC/bin/goblin-init" --write "$PRO" --yes --with-mcp-config 2>&1); RC=$?
check "M8 init --write --with-mcp-config exits 0" "$([ "$RC" -eq 0 ] && echo 0 || echo 1)"
[ -f "$R/.mcp.json" ] && [ "$(cat "$R/.mcp.json")" = "$GEN" ]
check "M8 --with-mcp-config writes .mcp.json naming the gob server (the generated bytes)" "$?"
printf '%s' "$OUT" | grep -q 'wrote .*/\.mcp\.json'
check "M8 and the run says it wrote the registration" "$?"
OUT=$(cd "$R" && bash "$SRC/bin/goblin-init" --write "$PRO" --yes --with-mcp-config 2>&1); RC=$?
check "M8 a second identical --write exits 0 (ask-once: a no-op, not an overwrite)" "$([ "$RC" -eq 0 ] && echo 0 || echo 1)"
printf '%s' "$OUT" | grep -q 'already carries the generated registration'
check "M8 and names the no-op" "$?"
printf '{"mcpServers":{"gob":{"command":"node","args":["/team/own/gob.js"]}}}\n' > "$R/.mcp.json"
OUT=$(cd "$R" && bash "$SRC/bin/goblin-init" --write "$PRO" --yes --with-mcp-config 2>&1); RC=$?
check "M8 a customized .mcp.json does not fail the install (exit 0)" "$([ "$RC" -eq 0 ] && echo 0 || echo 1)"
printf '%s' "$OUT" | grep -qF 'kept '
check "M8 and the run says the customized registration is kept" "$?"
