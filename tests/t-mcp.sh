# ---- M7: protocol errors -------------------------------------------------------
# The parse-error answer is id:null, which no request is waiting on — pair it with a
# ping so the client stays open long enough to carry the line out.
OUT=$(printf 'not json at all\n%s\n' '{"jsonrpc":"2.0","id":9,"method":"ping"}' | python3 "$SRC/tests/mcp-client.py" "node $MCP" 2>&1)
printf '%s' "$OUT" | grep -q '"id":null,"error":{"code":-32700'
check "M7 an unparseable line is -32700 with id null" "$?"
