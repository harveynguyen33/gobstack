#!/usr/bin/env bash
# t-mcp.sh — `gob mcp`: the MCP stdio server over the vendored harness.
#
#   M1  the handshake: initialize echoes the client protocolVersion and answers with
#       serverInfo (name gob, the VERSION source) + capabilities.tools; ping answers {}
#   M2  tools/list returns exactly the three tools with semantic-trigger descriptions
#   M3  tools/call gob_verify on a GREEN fixture: the verdict line is PASS with the
#       passed/failed counts and every FAIL row (there are none) would carry a remedy
#   M4  tools/call gob_verify on a RED fixture: verdict FAIL, the row id is named and
#       the manifest remedy cell rides under it; an unknown --only id still exits the
#       verifier's own way and the tool says so (isError), never crashes
#   M5  tools/call gob_map_status: an undeclared map says so; a declared map reports
#       each feature, its verified: date, and resolution per entry path (resolves under
#       a real token, DOES-NOT under a dead one — the FM-02 read-only half)
#   M6  tools/call gob_init_status: the gob block, gates and engine version
#   M7  protocol errors: a parse error is -32700 with id null, an unknown method is
#       -32601, an unknown tool is an isError RESULT, a notification is never answered
#   M8  init --write registers the gob MCP server: it writes the generated .mcp.json
#       exactly once; a second run states the no-op; a customized file is KEPT, never
#       overwritten; the uninstall removes the generated bytes and KEEPS a customized one
#   M9  no network, no stray spawns: the server is exercised with an empty PATH root
#       (nothing but node and the verify subprocess can run) and asserts it never
#       spawns anything but bash->goblin-verify; PT-04 over the source tree keeps the
#       file free of any endpoint, address or fetch surface
#
# The client: a real JSON-RPC driver (tests/mcp-client.py, python3 stdlib) that speaks
# the wire — write line, read line, parse — not a grep over canned bytes.
#
# Everything runs in a mktemp sandbox with HOME pointed inside it; no test writes the
# real $HOME. Run by tests/run-tests.sh.
set -uo pipefail

SRC=$(cd "$(dirname "${BASH_SOURCE[0]}")/.."/ && pwd)
SRC=${SRC%/}
WORK=$(mktemp -d)
FAILFILE="$WORK/fails"; : > "$FAILFILE"
note() { printf '      %s\n' "$*"; }
check() {
  if [ "$2" -eq 0 ]; then note "ok   $1"; else note "FAIL $1"; printf '%s\n' "$1" >> "$FAILFILE"; fi
}
trap 'rm -rf "$WORK"' EXIT

CLIENT="python3 $SRC/tests/mcp-client.py"
MCP="$SRC/bin/goblin-mcp.js"

# send <json>... — the client pipes the lines, reads until each id is answered, prints
# one response per line. A notification (no id) draws no answer by protocol.
mcp() { # <server-cmd...> -- <request json> [more...]
  local srv="$1"; shift; [ "$1" = "--" ] && shift
  printf '%s\n' "$@" | $CLIENT "$srv"
}

# ---- the fixtures --------------------------------------------------------------
# models + practice: the installer's two machine inputs
printf 'the referenced standard\n' > "$WORK/standard.md"

new_fixture() { # <tag> — a seeded, installed, committed repo
  local tag="$1"
  R="$WORK/$tag"
  mkdir -p "$R"
  ( cd "$R" && git init -q -b main && git config user.name "Test Runner" \
      && git config user.email "runner@example.com" \
      && printf '# %s\n' "$tag" > README.md \
      && git add -A && git commit -q -m "chore: seed" )
  ( cd "$R" && bash "$SRC/bin/goblin-install" --target "$R" \
      --practice "$WORK/standard.md" >/dev/null 2>&1 )
  ( cd "$R" && git add -A && git commit -q -m "chore: install gobstack" )
  # the HANDOFF placeholder red is the one expected red; name a real HEAD to go green
  ( cd "$R" && HEAD_NOW=$(git rev-parse --short HEAD) \
      && sed -i "s/^- HEAD when this file was written: .*/- HEAD when this file was written: \`$HEAD_NOW\`/" HANDOFF.md \
      && git add -A && git commit -q -m "docs: HANDOFF names the HEAD it describes" )
}

# write_proposal <dir> — the minimal proposal `gob init --write` accepts (one gate, one
# feature whose entry path is the committed README). The same file M8 and M10 drive.
write_proposal() {
  local dir="$1" pro="$1/.gob-init-proposal.md"
  {
    printf '<!-- gob:begin (gobstack config — edit in place; the parser reads only this block) -->\n'
    printf 'gate_commit_cmd: true\nfeature_map: features/README.md\n'
    printf '<!-- gob:end -->\n'
    printf '\n## gob init summary\n\n- fixture\n\n## feature-map\n\n'
    printf '### features/README.md\n\n```md\n# Features\n\n- [readme](./readme.md) — the repo readme\n```\n\n'
    printf '### features/readme.md\n\n```md\n---\nfeature: readme\nentry_paths:\n  - README.md\nverified: never-driven (2024-01-01)\n---\n'
    printf '# readme\n\nx\n\n## Sub-features\n\n- x\n\n## How to get to it (user POV)\n\n- x\n\n## Driving it with bash\n\nRun `cat README.md`.\n\n## Gotchas\n\n- x\n```\n'
  } > "$pro"
  printf '%s\n' "$pro"
}

# ---- M1: the handshake ---------------------------------------------------------
OUT=$(cd "$WORK" && printf '%s\n%s\n%s\n' \
  '{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocolVersion":"2025-06-18","capabilities":{},"clientInfo":{"name":"t-mcp","version":"0"}}}' \
  '{"jsonrpc":"2.0","method":"notifications/initialized"}' \
  '{"jsonrpc":"2.0","id":2,"method":"ping"}' \
  | python3 "$SRC/tests/mcp-client.py" "node $MCP")
check "M1 the client got answers for both requests" "$([ "$(printf '%s\n' "$OUT" | grep -c '^{"jsonrpc"')" = "2" ] && echo 0 || echo 1)"
printf '%s' "$OUT" | grep -q '"id":1'
check "M1 initialize is answered under its own id" "$?"
printf '%s' "$OUT" | grep -q '"protocolVersion":"2025-06-18"'
check "M1 the server echoes the client protocolVersion" "$?"
printf '%s' "$OUT" | grep -q '"serverInfo":{"name":"gob"'
check "M1 serverInfo names the server gob" "$?"
printf '%s' "$OUT" | grep -q "\"version\":\"$(cat "$SRC/VERSION")\""
check "M1 serverInfo carries the VERSION source, not a copy" "$?"
printf '%s' "$OUT" | grep -q '"capabilities":{"tools"'
check "M1 capabilities declare tools" "$?"
printf '%s' "$OUT" | grep -q '"id":2,"result":{}'
check "M1 ping answers {}" "$?"

# ---- M1b: the initialized notification draws NO answer -------------------------
OUTN=$(printf '%s\n' '{"jsonrpc":"2.0","method":"notifications/initialized"}' \
  | python3 "$SRC/tests/mcp-client.py" "node $MCP")
[ -z "$OUTN" ]
check "M1b the initialized notification draws NO answer" "$?"

