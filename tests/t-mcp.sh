printf '%s' "$OUT" | grep -q 'Call this BEFORE reporting any coding task complete'
check "M2 gob_verify's description is the semantic trigger" "$?"
printf '%s' "$OUT" | grep -q 'inputSchema'
check "M2 every tool carries an inputSchema" "$?"

